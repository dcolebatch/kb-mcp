#!/usr/bin/env bash
# scripts/ab-eval.sh — A/B index + eval FastEmbed vs OpenAI-compatible (Ollama).
#
# Usage:
#   KB_MCP_BIN=./target/release/kb-mcp bash scripts/ab-eval.sh \
#     --kb-path /path/to/vault --golden /path/to/.kb-mcp-eval.yml
#
#   bash scripts/ab-eval.sh --skip-index ...   # reuse existing AB DBs
#   bash scripts/ab-eval.sh --only ollama ...
#
# Env:
#   KB_MCP_BIN            path to kb-mcp binary (required if not on PATH)
#   OLLAMA_EMBED_MODEL    default: nomic-embed-text
#   OLLAMA_EMBED_DIM      default: 768
#   OLLAMA_EMBED_URL      default: http://127.0.0.1:11434/v1/embeddings
#   FASTEMBED_MODEL       default: bge-m3
#   AB_WORKDIR            default: <repo>/tmp/kb-mcp-ab
#   AB_BASE_CONFIG        optional toml to clone exclude/rerank/etc from

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"

KB_PATH=""
GOLDEN=""
SKIP_INDEX=0
ONLY=""
KB_MCP_BIN="${KB_MCP_BIN:-}"
OLLAMA_EMBED_MODEL="${OLLAMA_EMBED_MODEL:-nomic-embed-text}"
OLLAMA_EMBED_DIM="${OLLAMA_EMBED_DIM:-768}"
OLLAMA_EMBED_URL="${OLLAMA_EMBED_URL:-http://127.0.0.1:11434/v1/embeddings}"
FASTEMBED_MODEL="${FASTEMBED_MODEL:-bge-m3}"
AB_WORKDIR="${AB_WORKDIR:-$REPO_ROOT/tmp/kb-mcp-ab}"
AB_BASE_CONFIG="${AB_BASE_CONFIG:-}"

usage() {
  sed -n '2,20p' "$0" | sed 's/^# \?//'
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --kb-path) KB_PATH="$2"; shift 2 ;;
    --golden) GOLDEN="$2"; shift 2 ;;
    --skip-index) SKIP_INDEX=1; shift ;;
    --only) ONLY="$2"; shift 2 ;;
    -h|--help) usage; exit 0 ;;
    *) echo "unknown arg: $1" >&2; usage >&2; exit 2 ;;
  esac
done

die() { echo "error: $*" >&2; exit 1; }

[[ -n "$KB_PATH" ]] || die "--kb-path is required"
KB_PATH="$(cd "$KB_PATH" && pwd)"
[[ -d "$KB_PATH" ]] || die "kb-path is not a directory: $KB_PATH"

if [[ -z "$GOLDEN" ]]; then
  GOLDEN="$KB_PATH/.kb-mcp-eval.yml"
fi
[[ -f "$GOLDEN" ]] || die "golden file not found: $GOLDEN"

if [[ -z "$KB_MCP_BIN" ]]; then
  if command -v kb-mcp >/dev/null 2>&1; then
    KB_MCP_BIN="$(command -v kb-mcp)"
  elif [[ -x "$REPO_ROOT/target/release/kb-mcp" ]]; then
    KB_MCP_BIN="$REPO_ROOT/target/release/kb-mcp"
  else
    die "set KB_MCP_BIN to a kb-mcp binary that supports [embedding]"
  fi
fi
[[ -x "$KB_MCP_BIN" ]] || die "KB_MCP_BIN not executable: $KB_MCP_BIN"

WORK_PARENT="$(dirname "$KB_PATH")"
ACTIVE_DB="$WORK_PARENT/.kb-mcp.db"
RESULTS_DIR="$AB_WORKDIR/results"
CFG_DIR="$AB_WORKDIR/configs"
mkdir -p "$RESULTS_DIR" "$CFG_DIR"

variants=()
if [[ -z "$ONLY" || "$ONLY" == "fastembed" ]]; then
  variants+=(fastembed)
fi
if [[ -z "$ONLY" || "$ONLY" == "ollama" ]]; then
  variants+=(ollama)
fi
[[ ${#variants[@]} -gt 0 ]] || die "--only must be fastembed or ollama"

# --- preflight Ollama when needed ---
need_ollama=0
for v in "${variants[@]}"; do
  [[ "$v" == "ollama" ]] && need_ollama=1
done
if [[ "$need_ollama" -eq 1 ]]; then
  body="$(curl -sS --max-time 60 "$OLLAMA_EMBED_URL" -H 'Content-Type: application/json' \
    -d "{\"model\":\"$OLLAMA_EMBED_MODEL\",\"input\":\"ping\"}" || true)"
  echo "$body" | grep -q '"embedding"' \
    || die "Ollama embeddings not reachable at $OLLAMA_EMBED_URL (model=$OLLAMA_EMBED_MODEL). Is ollama serve running? body=${body:0:200}"
fi

# --- write variant configs (only copy safe keys from optional base) ---
EXCLUDE_DIRS='[".git", ".obsidian", "node_modules", "target", ".vscode", ".idea", ".cursor", "tmp", ".worktrees", ".pair"]'
if [[ -n "$AB_BASE_CONFIG" && -f "$AB_BASE_CONFIG" ]]; then
  extracted="$(python3 - "$AB_BASE_CONFIG" <<'PY'
import sys
try:
    import tomllib
except ImportError:
    import tomli as tomllib  # type: ignore
with open(sys.argv[1], "rb") as f:
    data = tomllib.load(f)
dirs = data.get("exclude_dirs")
if isinstance(dirs, list) and dirs:
    import json
    print(json.dumps(dirs))
PY
)" || extracted=""
  if [[ -n "$extracted" ]]; then
    EXCLUDE_DIRS="$extracted"
  fi
fi

write_fastembed_cfg() {
  local out="$1"
  cat >"$out" <<EOF
# generated by scripts/ab-eval.sh — FastEmbed variant
kb_path = "$KB_PATH"
model = "$FASTEMBED_MODEL"
reranker = "none"
exclude_dirs = $EXCLUDE_DIRS

[parsers]
enabled = ["md"]

[quality_filter]
enabled = true
threshold = 0.3

[search]
min_confidence_ratio = 1.5
EOF
}

write_ollama_cfg() {
  local out="$1"
  cat >"$out" <<EOF
# generated by scripts/ab-eval.sh — Ollama OpenAI-compatible variant
kb_path = "$KB_PATH"
reranker = "none"
exclude_dirs = $EXCLUDE_DIRS

[parsers]
enabled = ["md"]

[quality_filter]
enabled = true
threshold = 0.3

[search]
min_confidence_ratio = 1.5

[embedding]
provider = "openai-compatible"
endpoint = "$OLLAMA_EMBED_URL"
model = "$OLLAMA_EMBED_MODEL"
dimension = $OLLAMA_EMBED_DIM
timeout_seconds = 120
batch_size = 32
EOF
}

write_fastembed_cfg "$CFG_DIR/fastembed.toml"
write_ollama_cfg "$CFG_DIR/ollama.toml"

db_for() {
  echo "$WORK_PARENT/.kb-mcp-ab-$1.db"
}

# Snapshot / restore active DB so the live daemon is not left on an AB file.
RESTORE_ACTIVE=""
ACTIVE_BACKUP=""
cleanup() {
  if [[ -n "$ACTIVE_BACKUP" && -e "$ACTIVE_BACKUP" ]]; then
    rm -f "$ACTIVE_DB" "$ACTIVE_DB-journal" "$ACTIVE_DB-wal" "$ACTIVE_DB-shm" 2>/dev/null || true
    mv "$ACTIVE_BACKUP" "$ACTIVE_DB"
    echo "restored active DB -> $ACTIVE_DB"
  elif [[ -n "$RESTORE_ACTIVE" ]]; then
    # no prior DB; leave last AB parked, remove active if we created it
    :
  fi
}
trap cleanup EXIT

if [[ -e "$ACTIVE_DB" || -L "$ACTIVE_DB" ]]; then
  ACTIVE_BACKUP="$AB_WORKDIR/active-db-backup.db"
  rm -f "$ACTIVE_BACKUP"
  mv "$ACTIVE_DB" "$ACTIVE_BACKUP"
  # also park sidecar files if present
  for s in journal wal shm; do
    if [[ -e "$ACTIVE_DB-$s" ]]; then
      mv "$ACTIVE_DB-$s" "$ACTIVE_BACKUP-$s" 2>/dev/null || true
    fi
  done
  echo "parked active DB at $ACTIVE_BACKUP"
fi

activate_db() {
  local name="$1"
  local src
  src="$(db_for "$name")"
  rm -f "$ACTIVE_DB" "$ACTIVE_DB-journal" "$ACTIVE_DB-wal" "$ACTIVE_DB-shm" 2>/dev/null || true
  if [[ -e "$src" ]]; then
    # hard-link when possible so index writes update the AB file in place
    if ln "$src" "$ACTIVE_DB" 2>/dev/null; then
      :
    else
      cp -a "$src" "$ACTIVE_DB"
    fi
  fi
}

persist_active_to_ab() {
  local name="$1"
  local dest
  dest="$(db_for "$name")"
  rm -f "$dest"
  if [[ -e "$ACTIVE_DB" ]]; then
    if ln "$ACTIVE_DB" "$dest" 2>/dev/null; then
      :
    else
      cp -a "$ACTIVE_DB" "$dest"
    fi
  fi
}

index_meta_model() {
  local db="$1"
  [[ -f "$db" ]] || { echo ""; return; }
  sqlite3 "$db" "SELECT value FROM index_meta WHERE key='embedding_model';" 2>/dev/null || echo ""
}

run_variant() {
  local name="$1"
  local cfg="$CFG_DIR/$name.toml"
  local out_json="$RESULTS_DIR/$name.json"
  local timing_file="$RESULTS_DIR/$name.timing.txt"

  echo ""
  echo "=== variant: $name ==="
  activate_db "$name"

  local expected_model=""
  if [[ "$name" == "fastembed" ]]; then
    expected_model="$FASTEMBED_MODEL"
  else
    expected_model="openai:$OLLAMA_EMBED_MODEL"
  fi

  local do_index=1
  if [[ "$SKIP_INDEX" -eq 1 ]]; then
    do_index=0
    local existing
    existing="$(index_meta_model "$(db_for "$name")")"
    [[ -n "$existing" ]] || die "--skip-index but no AB DB for $name at $(db_for "$name")"
    echo "skip-index: using existing model=$existing"
  elif [[ "$name" == "fastembed" && -f "$ACTIVE_BACKUP" ]]; then
    # Seed fastembed AB DB from the parked live DB when models match (avoids a long reindex).
    local live_model
    live_model="$(index_meta_model "$ACTIVE_BACKUP")"
    if [[ "$live_model" == "$expected_model" ]]; then
      echo "seeding fastembed AB DB from parked live index ($live_model)"
      cp -a "$ACTIVE_BACKUP" "$(db_for fastembed)"
      for s in journal wal shm; do
        [[ -e "$ACTIVE_BACKUP-$s" ]] && cp -a "$ACTIVE_BACKUP-$s" "$(db_for fastembed)-$s" || true
      done
      activate_db fastembed
      do_index=0
    fi
  fi

  if [[ "$do_index" -eq 1 ]]; then
    echo "indexing with $cfg ..."
    local start end
    start="$(date +%s)"
    "$KB_MCP_BIN" --config "$cfg" index --kb-path "$KB_PATH" --force --progress
    end="$(date +%s)"
    echo "$((end - start))" >"$timing_file"
    echo "index wall seconds: $((end - start))"
    persist_active_to_ab "$name"
  else
    echo "0" >"$timing_file"
    echo "index skipped"
  fi

  echo "evaluating ..."
  "$KB_MCP_BIN" --config "$cfg" eval \
    --kb-path "$KB_PATH" \
    --golden "$GOLDEN" \
    --format json \
    --no-history \
    --no-diff \
    >"$out_json"
  echo "wrote $out_json"
}

for v in "${variants[@]}"; do
  run_variant "$v"
done

# --- compare ---
COMPARE_MD="$RESULTS_DIR/compare.md"
COMPARE_JSON="$RESULTS_DIR/compare.json"
python3 - "$RESULTS_DIR" "${variants[*]}" "$COMPARE_MD" "$COMPARE_JSON" <<'PY'
import json, sys, pathlib
results_dir = pathlib.Path(sys.argv[1])
variants = sys.argv[2].split()
out_md = pathlib.Path(sys.argv[3])
out_json = pathlib.Path(sys.argv[4])

def load(name):
    p = results_dir / f"{name}.json"
    data = json.loads(p.read_text())
    # eval --format json wraps or is the run; accept either
    if "aggregate" in data:
        run = data
    elif "run" in data and "aggregate" in data["run"]:
        run = data["run"]
    else:
        # format_json returns {timestamp,fingerprint,aggregate,per_query,diff?}
        run = data
    timing = 0
    tf = results_dir / f"{name}.timing.txt"
    if tf.exists():
        timing = int(tf.read_text().strip() or "0")
    return run, timing

rows = {}
for v in variants:
    run, timing = load(v)
    agg = run["aggregate"]
    rows[v] = {
        "model": run.get("fingerprint", {}).get("model"),
        "mrr": agg.get("mrr"),
        "recall_at_k": agg.get("recall_at_k", {}),
        "ndcg_at_k": agg.get("ndcg_at_k", {}),
        "query_count": agg.get("query_count"),
        "index_seconds": timing,
        "per_query": run.get("per_query", []),
    }

lines = ["# kb-mcp A/B eval comparison", ""]

def fmt(x):
    if x is None:
        return "—"
    if isinstance(x, float):
        return f"{x:.4f}"
    return str(x)

def delta(x, y):
    if x is None or y is None:
        return "—"
    return f"{(y - x):+.4f}"

if len(variants) == 2:
    a, b = variants[0], variants[1]
    lines.append(f"Comparing **{a}** (`{rows[a]['model']}`) vs **{b}** (`{rows[b]['model']}`).")
    lines.append("")
    lines.append(f"| metric | {a} | {b} | delta ({b} - {a}) |")
    lines.append("| --- | ---: | ---: | ---: |")
    lines.append(f"| MRR | {fmt(rows[a]['mrr'])} | {fmt(rows[b]['mrr'])} | {delta(rows[a]['mrr'], rows[b]['mrr'])} |")
    lines.append(
        f"| index_seconds | {rows[a]['index_seconds']} | {rows[b]['index_seconds']} | "
        f"{rows[b]['index_seconds'] - rows[a]['index_seconds']:+d} |"
    )
    keys = sorted(set(rows[a]['recall_at_k']) | set(rows[b]['recall_at_k']), key=lambda k: int(k))
    for k in keys:
        va = rows[a]['recall_at_k'].get(str(k), rows[a]['recall_at_k'].get(k))
        vb = rows[b]['recall_at_k'].get(str(k), rows[b]['recall_at_k'].get(k))
        lines.append(f"| recall@{k} | {fmt(va)} | {fmt(vb)} | {delta(va, vb)} |")
    keys = sorted(set(rows[a]['ndcg_at_k']) | set(rows[b]['ndcg_at_k']), key=lambda k: int(k))
    for k in keys:
        va = rows[a]['ndcg_at_k'].get(str(k), rows[a]['ndcg_at_k'].get(k))
        vb = rows[b]['ndcg_at_k'].get(str(k), rows[b]['ndcg_at_k'].get(k))
        lines.append(f"| ndcg@{k} | {fmt(va)} | {fmt(vb)} | {delta(va, vb)} |")

    lines.append("")
    lines.append("## Per-query deltas (non-zero recall@k only)")
    lines.append("")
    by_id_a = {q.get('id') or q.get('query'): q for q in rows[a]['per_query']}
    by_id_b = {q.get('id') or q.get('query'): q for q in rows[b]['per_query']}
    lines.append(f"| query | metric | {a} | {b} | delta |")
    lines.append("| --- | --- | ---: | ---: | ---: |")
    for qid in sorted(set(by_id_a) | set(by_id_b)):
        qa, qb = by_id_a.get(qid), by_id_b.get(qid)
        if not qa or not qb:
            continue
        ra = qa.get('metrics', {}).get('recall_at_k', {})
        rb = qb.get('metrics', {}).get('recall_at_k', {})
        candidates = sorted({str(k) for k in list(ra) + list(rb)}, key=lambda x: int(x))
        k = '5' if '5' in candidates else (candidates[0] if candidates else None)
        if k is None:
            continue
        va, vb = ra.get(k, ra.get(int(k) if k.isdigit() else k)), rb.get(k, rb.get(int(k) if k.isdigit() else k))
        if va is None or vb is None:
            continue
        if abs(vb - va) < 1e-9:
            continue
        label = (qa.get('query') or qid)[:60].replace('|', '/')
        lines.append(f"| {label} | recall@{k} | {va:.4f} | {vb:.4f} | {vb-va:+.4f} |")
else:
    for v in variants:
        lines.append(f"## {v} (`{rows[v]['model']}`)")
        lines.append(f"- MRR: {rows[v]['mrr']}")
        lines.append(f"- recall_at_k: {rows[v]['recall_at_k']}")
        lines.append(f"- ndcg_at_k: {rows[v]['ndcg_at_k']}")
        lines.append(f"- index_seconds: {rows[v]['index_seconds']}")
        lines.append("")

out_md.write_text("\n".join(lines) + "\n")
out_json.write_text(json.dumps(rows, indent=2) + "\n")
print(f"wrote {out_md}")
print(f"wrote {out_json}")
print("---")
print(out_md.read_text())
PY

echo "A/B eval complete."
